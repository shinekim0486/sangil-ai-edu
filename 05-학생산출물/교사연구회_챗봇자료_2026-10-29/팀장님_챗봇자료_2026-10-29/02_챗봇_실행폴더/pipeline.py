def _signal_present(text, word):
    # 'ntp'가 일반 문자열 일부와 우연히 일치하지 않도록 영문 토큰 경계를 검사한다.
    import re
    if word.isascii() and word.replace(" ", "").isalnum():
        return bool(re.search(r"(?<![a-z0-9_])" + re.escape(word) + r"(?![a-z0-9_])", text))
    return word in text


def resolve_step(text, current=None, model_step=None):
    """교과 선언 → 명확한 기술 화제 → 기존 문맥 → 모델 순으로 공정을 정한다.

    기존 공정과 다른 강한 근거가 없으면 '검증/출력/충돌/시작'만으로 이동하지 않는다.
    명시적 교과 전환 및 프로토콜·CAD 같은 구체적 기술 화제 전환은 허용한다.
    """
    import re
    t = (text or "").lower()
    declared = [sid for pattern, sid in _COURSE_ROUTES if re.search(pattern, t)]
    if len(set(declared)) == 1:
        return declared[0]
    is_3d = bool(re.search(r"3d\s*(?:제품|프린터)|3차원\s*제품", t))
    if is_3d:
        if re.search(r"cad\s*설계|설계반|스케치\s*설계", t):
            return "B1"
        if re.search(r"출력[·ㆍ/\s-]*조립|출력반|조립반|출력물|슬라이서", t):
            return "B2"
        if current in ("B1", "B2"):
            return current
    scores = {sid: sum(len(word) for word in words if _signal_present(t, word))
              for sid, words in _ROUTE_SIGNALS.items()}
    ranked = sorted(((score, sid) for sid, score in scores.items() if score), reverse=True)
    if ranked:
        score, sid = ranked[0]
        if current in STEP_BY_ID:
            # 현재 공정에도 기술 근거가 있으면 유지한다. 그렇지 않을 때만 강한 화제로 전환한다.
            if (scores.get(current, 0) or score < 3
                    or (sid == 'D1' and score == len('재부팅') and '재부팅' in t)):
                return current
        return sid
    if current in STEP_BY_ID:
        return current
    return model_step if model_step in STEP_BY_ID else None


def declared_step(text):
    """첫 질문의 명시적 교과 선언만 추출한다. 기술 낱말 점수는 사용하지 않는다."""
    import re
    t = (text or '').lower()
    declared = {sid for pattern, sid in _COURSE_ROUTES if re.search(pattern, t)}
    if len(declared) == 1:
        return declared.pop()
    if re.search(r'3d\s*(?:제품|프린터)|3차원\s*제품', t):
        if re.search(r'cad\s*설계|설계반', t):
            return 'B1'
        if re.search(r'출력[·ㆍ/\s-]*조립|출력반|조립반', t):
            return 'B2'
    return None


def hint_for(text):
    """시스템 프롬프트에 넣을 후보 안내. 없으면 빈 문자열."""
    cand = guess_steps(text)
    if not cand:
        return ""
    lines = ["[이번 학생 말에서 짚이는 단계 — 서버가 낱말로 골랐다]"]
    for sid in cand:
        s = STEP_BY_ID.get(sid)
        if not s:
            continue
        subj = " · ".join(SUBJECT[k] for k in s["subjects"]) or "전 과목"
        lines.append("  %s %s [%s] — %s" % (sid, s["name"], subj, s["done"]))
    lines.append("→ 이 중 하나가 맞으면 step에 그 값을 넣어라. "
                 "전부 아니면 다른 단계를 골라도 되고, 정말 모르겠으면 null로 둔다.")
    return chr(10).join(lines)
