def spec_table():
    """P0 단계 상세에 넣는 전체 표."""
    lines = ["[프로젝트 표준 규격 — 전체]"]
    for g in SPEC_GROUPS:
        rows = [r for r in SPEC if r[0] == g]
        if not rows:
            continue
        lines.append("· " + g)
        for _, item, value, status, note in rows:
            mark = "" if status == "확정" else " (잠정 — " + note + ")"
            lines.append("    " + item + ": " + value + mark)
    return chr(10).join(lines)


