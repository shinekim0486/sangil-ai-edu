def brief():
    """시스템 프롬프트에 항상 넣는 전 과정 요약. 짧게 유지한다."""
    lines = ["[자율주행자동차 제작 전 과정]",
             "A코스와 B코스가 나란히 진행되다가 C에서 만난다. "
             "D 운영은 1주차부터 6주 내내 상시로 돌아간다."]
    cur = None
    for s in STEPS:
        if s["course"] != cur:
            cur = s["course"]
            lines.append("")
            lines.append("· " + COURSES[cur])
        subj = "/".join(SUBJECT[k] for k in s["subjects"]) or "전 과목"
        mark = " (평가 대상 아님)" if s["id"] in UNGRADED else ""
        if s["id"] in ALWAYS_ON:
            mark += " (상시)"
        need = NEEDS.get(s["id"]) or []
        pre = ("  ←먼저: " + "·".join(need)) if need else ""
        cue = CUES.get(s["id"], "")
        lines.append("  %s %s [%s]%s%s"
                     % (s["id"], s["name"], subj, mark, pre))
        if cue:
            lines.append("      이런 말이 나오면 이 단계: %s" % cue)
    return "\n".join(lines)


