def guess_steps(text, limit=3):
    """학생 말에서 단계 후보를 뽑는다. 확실할수록 앞에 온다."""
    t = (text or "").lower()
    hits = []
    for sid, words in KEYWORDS.items():
        score = sum(len(w) for w in words if w in t)
        if score:
            hits.append((score, sid))
    hits.sort(reverse=True)
    return [sid for _, sid in hits[:limit]]


