def block(items, prefix="  - "):
    return "\n".join(prefix + x for x in items) if items else prefix + "(없음)"


def links_of(s):
    out = []
    if s["gets"]:
        out.append("**받는 것**")
        out += ["  - %s ← %s" % (b, a) for a, b in s["gets"]]
    if s["gives"]:
        out.append("**주는 것**")
        out += ["  - %s → %s" % (b, a) for a, b in s["gives"]]
    if not out:
        out = ["(직접 주고받는 산출물 없음)"]
    out.append("")
    out.append("범위 밖 질문이 오면 담당 과목을 알려 주고 그 팀에 요청하라고 안내한다.")
    return "\n".join(out)


made, kept = [], []
for s in SKILLS:
    path = os.path.join(OUT, s["fid"] + ".md")
    if os.path.exists(path):
        kept.append(s["fid"])
        continue
    body = TPL.format(
        subject=s["subject"], teacher=s["teacher"], course=s["course"],
        ncs=s["ncs"], elements=block(s["elements"]), codes=s["codes"],
        outside=block(s["outside"]), makes=s["makes"], links=links_of(s),
    )
    io.open(path, "w", encoding="utf-8").write(body)
    made.append(s["fid"])

print("생성 %d개: %s" % (len(made), ", ".join(made) or "-"))
print("유지 %d개: %s" % (len(kept), ", ".join(kept) or "-"))
